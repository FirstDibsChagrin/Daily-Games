/* Upserts the game catalog (lib/catalog-data.ts) into catalog_games.
   Usage: npm run db:seed            -> writes to the database
          npm run db:seed:sql        -> regenerates supabase/seed.sql */
import "dotenv/config";
import { writeFileSync } from "node:fs";
import postgres from "postgres";
import { CATALOG } from "../lib/catalog-data";

function lit(v: string | number | boolean | null): string {
  if (v === null) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${v.replace(/'/g, "''")}'`;
}

const COLS = [
  "key",
  "name",
  "entry_prompt",
  "entry_example",
  "input_type",
  "min",
  "max",
  "direction",
  "allow_fail",
  "unit_label",
  "url",
  "color",
  "verified",
  "note",
] as const;

export function seedSql(): string {
  const rows = CATALOG.map((g) => `  (${COLS.map((c) => lit(g[c])).join(", ")})`).join(",\n");
  const updates = COLS.filter((c) => c !== "key")
    .map((c) => `${c} = excluded.${c}`)
    .join(",\n  ");
  return `-- Generated by scripts/seed.ts from lib/catalog-data.ts. Do not edit by hand.
insert into public.catalog_games (${COLS.join(", ")}) values
${rows}
on conflict (key) do update set
  ${updates};
`;
}

async function main() {
  if (process.argv.includes("--sql")) {
    writeFileSync("supabase/seed.sql", seedSql());
    console.log("wrote supabase/seed.sql");
    return;
  }
  const url = process.env.DATABASE_ADMIN_URL ?? process.env.DATABASE_URL;
  if (!url) throw new Error("Set DATABASE_ADMIN_URL (or DATABASE_URL)");
  const sql = postgres(url, { max: 1, onnotice: () => {} });
  await sql.unsafe(seedSql());
  await sql.end();
  console.log(`seeded ${CATALOG.length} catalog games`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
