-- Daily League: initial schema
-- All access happens server-side through the `daily_league_app` role.
-- RLS is enabled on every table; the only policies are for that role, so the
-- Supabase `anon` / `authenticated` keys (PostgREST) can read nothing.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- App role (password is set separately, never in a migration)
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'daily_league_app') then
    create role daily_league_app nologin;
  end if;
end
$$;

-- ---------------------------------------------------------------------------
-- Leagues and members
-- ---------------------------------------------------------------------------
create table public.leagues (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 40),
  -- permanent URL key (the first join code); never changes
  slug text not null unique check (slug ~ '^[A-Z2-9]{6}$'),
  -- current join code; can be regenerated by the creator
  join_code text not null unique check (join_code ~ '^[A-Z2-9]{6}$'),
  points_table integer[] not null default '{5,3,2,1}'
    check (array_length(points_table, 1) between 1 and 20),
  created_at timestamptz not null default now()
);

create table public.members (
  id uuid primary key default gen_random_uuid(),
  league_id uuid not null references public.leagues(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 20),
  pin_hash text not null,
  is_creator boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index members_league_name_ci on public.members (league_id, lower(name));
create index members_league on public.members (league_id);

create table public.member_sessions (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.members(id) on delete cascade,
  token_hash text not null unique,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);
create index member_sessions_member on public.member_sessions (member_id);

-- DB-backed rate limiting / lockouts (serverless has no shared memory)
create table public.rate_limits (
  key text primary key,
  attempts integer not null default 0,
  window_start timestamptz not null default now(),
  locked_until timestamptz
);

-- ---------------------------------------------------------------------------
-- Games
-- ---------------------------------------------------------------------------
create table public.catalog_games (
  key text primary key check (key ~ '^[a-z0-9-]+$'),
  name text not null,
  entry_prompt text not null,
  entry_example text not null,
  input_type text not null check (input_type in ('integer', 'decimal', 'time')),
  min numeric not null,
  max numeric not null,
  direction text not null check (direction in ('lower_is_better', 'higher_is_better')),
  allow_fail boolean not null default false,
  unit_label text,
  url text,
  color text not null check (color ~ '^#[0-9a-fA-F]{6}$'),
  verified boolean not null default true,
  note text,
  check (min <= max)
);

create table public.league_games (
  id uuid primary key default gen_random_uuid(),
  league_id uuid not null references public.leagues(id) on delete cascade,
  catalog_key text references public.catalog_games(key) on delete set null,
  name text not null check (char_length(name) between 1 and 40),
  entry_prompt text not null check (char_length(entry_prompt) between 1 and 300),
  entry_example text not null default '' check (char_length(entry_example) <= 60),
  input_type text not null check (input_type in ('integer', 'decimal', 'time')),
  min numeric not null,
  max numeric not null,
  direction text not null check (direction in ('lower_is_better', 'higher_is_better')),
  allow_fail boolean not null default false,
  color text not null check (color ~ '^#[0-9a-fA-F]{6}$'),
  sort_order integer not null default 0,
  url text,
  unit_label text check (unit_label is null or char_length(unit_label) <= 12),
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  check (min <= max)
);
create index league_games_league on public.league_games (league_id, sort_order);

-- ---------------------------------------------------------------------------
-- Scores (points are never stored; they are computed live)
-- ---------------------------------------------------------------------------
create table public.scores (
  id uuid primary key default gen_random_uuid(),
  league_id uuid not null references public.leagues(id) on delete cascade,
  member_id uuid not null references public.members(id) on delete cascade,
  game_id uuid not null references public.league_games(id) on delete cascade,
  play_date date not null,
  value numeric,
  failed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (member_id, game_id, play_date),
  check ((value is null) = failed)
);
create index scores_league_date on public.scores (league_id, play_date);
create index scores_game on public.scores (game_id);

-- ---------------------------------------------------------------------------
-- Suggestions and badges
-- ---------------------------------------------------------------------------
create table public.game_suggestions (
  id uuid primary key default gen_random_uuid(),
  league_id uuid not null references public.leagues(id) on delete cascade,
  member_id uuid references public.members(id) on delete set null,
  name text not null check (char_length(name) between 1 and 40),
  url text check (url is null or char_length(url) <= 300),
  description text not null default '' check (char_length(description) <= 500),
  status text not null default 'pending' check (status in ('pending', 'approved', 'dismissed')),
  created_at timestamptz not null default now()
);
create index game_suggestions_league on public.game_suggestions (league_id, status);

create table public.badge_awards (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.members(id) on delete cascade,
  badge_key text not null,
  context_key text not null default '',
  -- the game day on which the badge was earned (derived from data)
  earned_on date not null,
  awarded_at timestamptz not null default now(),
  unique (member_id, badge_key, context_key)
);

-- ---------------------------------------------------------------------------
-- Lock everything down
-- ---------------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array[
    'leagues', 'members', 'member_sessions', 'rate_limits', 'catalog_games',
    'league_games', 'scores', 'game_suggestions', 'badge_awards'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format(
      'create policy app_all on public.%I for all to daily_league_app using (true) with check (true)',
      t
    );
    execute format('grant select, insert, update, delete on public.%I to daily_league_app', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on public.%I from anon', t);
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
      execute format('revoke all on public.%I from authenticated', t);
    end if;
  end loop;
end
$$;

grant usage on schema public to daily_league_app;
